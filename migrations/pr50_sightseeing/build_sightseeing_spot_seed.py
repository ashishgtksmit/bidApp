#!/usr/bin/env python3
"""Build seed_sightseeing_spots.sql and seed_report.md from WizzRide sources.

Reads (no database connection):
  wizridehome-master/database/migrations/002_sightseeing_v2_seed_gangtok.sql
  wizridehome-master/database/migrations/021_sightseeing_v2_private_catalogue.sql
  wizridehome-master/database/migrations/044_sightseeing_v2_permit_seed_pending.sql

The generated SQL resolves each WizzRide location to location_details.LID by
name at apply time and inserts only spots whose spotCode is not present yet.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

MIG_DIR = Path(__file__).resolve().parent
DEFAULT_SOURCE = Path(__file__).resolve().parents[4] / "wizridehome-master" / "database" / "migrations"
SOURCE = Path(os.getenv("WIZZRIDE_MIGRATIONS_DIR", str(DEFAULT_SOURCE)))

sys.path.insert(0, str(MIG_DIR))
from _db import SPOTS_TABLE, WIZZRIDE_LOCATION_NAMES  # noqa: E402

SEED_SQL = MIG_DIR / "seed_sightseeing_spots.sql"
REPORT = MIG_DIR / "seed_report.md"

# Points that are not places a customer can pick.
PLACEHOLDER_CODES = {
    "PHOTO_STOPS": "placeholder, not a place",
    "HIGH_ALTITUDE_VIEWS": "placeholder, not a place",
    "TSOMGO_STOP": "duplicate of TSOMGO_LAKE",
    "INDO_CHINA_BORDER": "part of NATHULA_PASS",
    "BAN_JHAKRI_FALLS": "duplicate of BANJHAKRI_FALLS",
    "LGCY_SP_10": "duplicate of CABLE_CAR",
}

DAY_ROUTE = re.compile(r"^\s*day\s*0?\d+\s*:", re.IGNORECASE)
PRICE_NOTE = re.compile(r"\s*\(\s*optional[^)]*\)\s*$", re.IGNORECASE)

POINT_002 = re.compile(
    r"INSERT INTO `ss_points`.*?SELECT\s+`location_id`,\s*'([A-Z0-9_]+)',\s*'((?:[^']|'')*)'"
    r".*?`location_code`\s*=\s*'([A-Z_]+)'",
    re.S,
)
POINT_021 = re.compile(
    r"INSERT INTO `ss_points`.*?SELECT src\.`location_id`,\s*'([A-Z0-9_]+)',\s*'((?:[^']|'')*)'"
    r".*?`location_code`\s*=\s*'([A-Z_]+)'",
    re.S,
)
PERMIT_BLOCK = re.compile(r"INSERT INTO `ss_permit_destinations`.*?FROM \((.*?)\) v", re.S)
PERMIT_DEST = re.compile(r"SELECT\s+'([A-Z_]+)'")


def _read(name: str) -> str:
    path = SOURCE / name
    if not path.exists():
        raise SystemExit(f"ERROR: source not found: {path}")
    return path.read_text(encoding="utf-8")


def _sql(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def collect():
    points: list[tuple[str, str, str, str]] = []  # (location, code, name, source)
    for name, pattern in (
        ("002_sightseeing_v2_seed_gangtok.sql", POINT_002),
        ("021_sightseeing_v2_private_catalogue.sql", POINT_021),
    ):
        for match in pattern.finditer(_read(name)):
            code, raw_name, location = match.group(1), match.group(2), match.group(3)
            points.append((location, code, raw_name.replace("''", "'"), name[:3]))

    permit_sql = _read("044_sightseeing_v2_permit_seed_pending.sql")
    block = PERMIT_BLOCK.search(permit_sql)
    if not block:
        raise SystemExit("ERROR: permit destinations block not found in migration 044.")
    permit_codes = set(PERMIT_DEST.findall(block.group(1)))
    known_codes = {code for _, code, _, _ in points}
    missing = permit_codes - known_codes
    if missing:
        raise SystemExit(f"ERROR: permit destinations not found as points: {sorted(missing)}")

    kept, skipped, renamed = [], [], []
    seen = set()
    for location, code, name, source in points:
        if code in seen:
            continue
        seen.add(code)
        if code in PLACEHOLDER_CODES:
            skipped.append((location, code, name, PLACEHOLDER_CODES[code]))
            continue
        if DAY_ROUTE.match(name):
            skipped.append((location, code, name, "day route description, not a place"))
            continue
        clean = PRICE_NOTE.sub("", name).strip()
        if clean != name:
            renamed.append((code, name, clean))
        kept.append((location, code, clean, 1 if code in permit_codes else 0))
    return kept, skipped, renamed, sorted(permit_codes)


def build() -> int:
    kept, skipped, renamed, permit_codes = collect()
    order: dict[str, int] = {}
    lines = [
        "-- Generated by build_sightseeing_spot_seed.py. Do not edit by hand.",
        "-- Idempotent: inserts only missing spotCode values.",
        "-- Location resolved by exact location_details.location name; unmatched or",
        "-- ambiguous names insert nothing for that location.",
        "",
    ]
    for location, code, name, permit in kept:
        order[location] = order.get(location, 0) + 10
        names = WIZZRIDE_LOCATION_NAMES.get(location, [])
        if not names:
            continue
        name_list = ", ".join(_sql(n.lower()) for n in names)
        lines.append(
            f"INSERT INTO {SPOTS_TABLE} (locationId, spotCode, spotName, permitRequired, isActive, sortOrder)\n"
            f"SELECT loc.LID, {_sql(code)}, {_sql(name)}, {permit}, 1, {order[location]}\n"
            f"FROM (SELECT MIN(LID) AS LID FROM location_details\n"
            f"      WHERE LOWER(TRIM(location)) IN ({name_list})\n"
            f"      HAVING COUNT(*) = 1) loc\n"
            f"WHERE loc.LID IS NOT NULL\n"
            f"  AND NOT EXISTS (SELECT 1 FROM {SPOTS_TABLE} s WHERE s.spotCode = {_sql(code)});\n"
        )
    SEED_SQL.write_text("\n".join(lines), encoding="utf-8")

    per_location: dict[str, list[tuple[str, str, int]]] = {}
    for location, code, name, permit in kept:
        per_location.setdefault(location, []).append((code, name, permit))
    report = [
        "# PR50 sightseeing spot seed report",
        "",
        "Generated by `build_sightseeing_spot_seed.py` from the WizzRide Sightseeing V2",
        "migrations 002, 021 and 044. Review the items under **Needs review**.",
        "",
        f"- Spots to seed: **{len(kept)}**",
        f"- Permit-required spots: {', '.join(permit_codes) or 'none'}",
        "",
        "## Spots per WizzRide location",
        "",
    ]
    for location in sorted(per_location):
        report.append(f"### {location} ({len(per_location[location])})")
        report.append("")
        for code, name, permit in per_location[location]:
            report.append(f"- `{code}` {name}{' (permit)' if permit else ''}")
        report.append("")
    empty = sorted(set(WIZZRIDE_LOCATION_NAMES) - set(per_location))
    if empty:
        report += ["## Locations with no seedable spots", ""]
        report += [f"- {code}" for code in empty]
        report.append("")
    report += ["## Skipped source points", ""]
    report += [f"- {loc} `{code}` {name}: {reason}" for loc, code, name, reason in skipped]
    report += ["", "## Renamed (price note removed)", ""]
    report += [f"- `{code}`: \"{old}\" -> \"{new}\"" for code, old, new in renamed]
    report += [
        "",
        "## Needs review",
        "",
        "- Permit flags come only from the WizzRide permit destinations in migration 044.",
        "  Other permit areas (for example North Sikkim) are not flagged.",
        "- `LGCY_SP_16` Namchi and `LGCY_SP_41` Mirik are towns listed under Darjeeling in",
        "  the source data; they are seeded as-is.",
        "- North Sikkim source points are whole-day routes, so that location has no spots.",
        "",
    ]
    REPORT.write_text("\n".join(report), encoding="utf-8")
    print(f"Wrote {SEED_SQL.name} ({len(kept)} spots) and {REPORT.name}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(build())
